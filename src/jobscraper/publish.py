"""Turn Sheet rows into publishable Neon rows (doc 13). Pure functions, no I/O.

What: validates, converts and filters raw Jobs-tab rows (all strings) into typed rows.
Inputs: list of dicts keyed by Sheet header, a PublishSettings, and the run start time.
Outputs: a PublishPlan (rows to write, drop counts) and guard checks.
Failure behavior: a bad row is dropped and counted, never raised. Only the guard raises.

Note: the small converters below are self-contained so this module does not depend on the
private helpers in dashboard.py. If you later promote those to a shared module, swap them in.
"""

from __future__ import annotations

import json
import math
from collections import Counter
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from datetime import UTC, date, datetime, timedelta
from typing import Any
from zoneinfo import ZoneInfo

from pydantic import BaseModel, ConfigDict, Field

from jobscraper.utils.dates import parse_user_date

EAT = ZoneInfo("Africa/Nairobi")

TIERS = frozenset({"top", "strong", "potential", "weak", "unscored"})

# Column order written to Neon. `search` is generated by Postgres and is not listed.
COLUMNS: tuple[str, ...] = (
    "profile",
    "job_id",
    "title",
    "company",
    "location",
    "work_type",
    "employment_type",
    "remote_eligibility",
    "salary",
    "skills_matched",
    "skills_missing",
    "match_score",
    "match_tier",
    "scoring_version",
    "match_breakdown",
    "recommended_action",
    "source",
    "job_url",
    "date_posted",
    "application_deadline",
    "first_seen",
    "last_seen",
    "is_active",
    "is_repost",
    "description_excerpt",
    "checklist",
    "application_status",
    "published_at",
)


class PublishSettings(BaseModel):
    """The `publish:` block of config/settings.yaml. Every value has a safe default."""

    model_config = ConfigDict(extra="forbid")

    max_age_days: int = Field(default=30, ge=1)
    hide_statuses: list[str] = Field(default_factory=lambda: ["Ignored", "Rejected"])
    keep_statuses: list[str] = Field(default_factory=lambda: ["Applied", "Interview", "Offer"])
    guard_min_existing: int = Field(default=10, ge=1)
    guard_min_ratio: float = Field(default=0.5, ge=0.0, le=1.0)


class GuardError(RuntimeError):
    """Publishing would wipe or collapse the existing copy."""


@dataclass
class PublishPlan:
    rows: list[dict[str, Any]]
    dropped: Counter[str] = field(default_factory=Counter)
    sheet_rows: int = 0

    def summary(self) -> str:
        total_dropped = sum(self.dropped.values())
        text = f"Published {len(self.rows)}, dropped {total_dropped}"
        if self.dropped:
            parts = ", ".join(
                f"{n} {reason.replace('_', ' ')}" for reason, n in self.dropped.most_common()
            )
            text += f" ({parts})"
        return text


# ---------- converters ----------


def _text(value: object) -> str:
    """Strip and remove NUL characters (Postgres rejects them)."""
    return "" if value is None else str(value).replace("\x00", "").strip()


def _unescape(value: str) -> str:
    """Remove the one leading apostrophe the Sheet writer adds against formula injection."""
    return value[1:] if value.startswith("'") else value


def _or_none(value: str) -> str | None:
    return value or None


def _names(value: object) -> list[str]:
    """Semicolon-separated skills to a clean list."""
    return [p for p in (s.strip() for s in _text(value).split(";")) if p]


def _score(value: object) -> float | None:
    try:
        number = float(_text(value))
    except ValueError:
        return None
    if not math.isfinite(number) or not 0 <= number <= 100:
        return None
    return round(number, 1)


def _date(value: object) -> date | None:
    if value is None:
        return None
    if isinstance(value, (date, datetime)):
        return value.date() if isinstance(value, datetime) else value
    return parse_user_date(str(value))


def _timestamp(value: object) -> datetime | None:
    text = _text(value)
    if not text:
        return None
    try:
        parsed = datetime.fromisoformat(text.replace("Z", "+00:00"))
    except ValueError:
        return None
    return (parsed if parsed.tzinfo else parsed.replace(tzinfo=UTC)).astimezone(UTC)


def _breakdown(value: object) -> tuple[dict[str, Any] | None, int | None]:
    text = _text(value)
    if not text:
        return None, None
    try:
        data = json.loads(text)
    except ValueError:
        return None, None
    if not isinstance(data, dict):
        return None, None
    version = data.get("version")
    if (
        isinstance(version, int)
        and not isinstance(version, bool)
        and -2147483648 <= version <= 2147483647
    ):
        return data, version
    return data, None


