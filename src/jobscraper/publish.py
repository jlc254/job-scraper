def build_rows(
    sheet_rows: Iterable[Mapping[str, Any]],
    settings: PublishSettings,
    now: datetime,
    profile: str,
) -> PublishPlan:
    """Convert and filter Sheet rows per the doc 13 rules, for one profile (doc 15).

    `profile` is the profile id. It is written to every row, and Neon keys rows by
    (profile, job_id), so two profiles can never overwrite each other.

    `now` is the run start (timezone-aware). It becomes `published_at` on every row and
    defines "today" in Africa/Nairobi for the deadline rule.
    """
    now = now.astimezone(UTC)
    today = now.astimezone(EAT).date()
    cutoff = now - timedelta(days=settings.max_age_days)
    hide = {s.casefold() for s in settings.hide_statuses}
    keep = {s.casefold() for s in settings.keep_statuses}

    plan = PublishPlan(rows=[], sheet_rows=0)
    by_id: dict[str, dict[str, Any]] = {}

    for raw in sheet_rows:
        plan.sheet_rows += 1
        job_id = _text(raw.get("job_id"))
        title = _unescape(_text(raw.get("title")))
        company = _unescape(_text(raw.get("company")))
        if not (job_id and title and company):
            plan.dropped["missing_field"] += 1
            continue

        job_url = _text(raw.get("job_url"))
        if not job_url.lower().startswith(("http://", "https://")):
            plan.dropped["no_url"] += 1
            continue

        if _text(raw.get("is_active")).upper() == "FALSE":
            plan.dropped["inactive"] += 1
            continue

        deadline = _date(raw.get("application_deadline"))
        if deadline is not None and deadline < today:
            plan.dropped["expired"] += 1
            continue

        status = _text(raw.get("application_status")) or "New"
        if status.casefold() in hide:
            plan.dropped["hidden_status"] += 1
            continue

        first_seen = _timestamp(raw.get("first_seen"))
        if first_seen is None:
            plan.dropped["bad_timestamp"] += 1
            continue
        if first_seen < cutoff and status.casefold() not in keep:
            plan.dropped["too_old"] += 1
            continue

        breakdown, version = _breakdown(raw.get("match_breakdown"))
        tier = _text(raw.get("match_tier")).lower()

        row: dict[str, Any] = {
            "profile": profile,
            "job_id": job_id,
            "title": title,
            "company": company,
            "location": _or_none(_text(raw.get("location"))),
            "work_type": _text(raw.get("work_type")) or "unknown",
            "employment_type": _text(raw.get("employment_type")) or "unknown",
            "remote_eligibility": _text(raw.get("remote_eligibility")) or "unclear",
            "salary": _or_none(_text(raw.get("salary"))),
            "skills_matched": _names(raw.get("skills_matched")),
            "skills_missing": _names(raw.get("skills_missing")),
            "match_score": _score(raw.get("match_score")),
            "match_tier": tier if tier in TIERS else "unscored",
            "scoring_version": version,
            "match_breakdown": breakdown,
            "recommended_action": _or_none(_text(raw.get("recommended_action"))),
            "source": _text(raw.get("source")) or "unknown",
            "job_url": job_url,
            "date_posted": _date(raw.get("date_posted")),
            "application_deadline": deadline,
            "first_seen": first_seen,
            "last_seen": _timestamp(raw.get("last_seen")) or first_seen,
            "is_active": True,
            "is_repost": _text(raw.get("is_repost")).upper() == "TRUE",
            "description_excerpt": str(raw.get("description_excerpt") or "").replace("\x00", ""),
            "checklist": _or_none(_text(raw.get("checklist"))),
            "application_status": status,
            "published_at": now,
        }
        if job_id in by_id:
            plan.dropped["duplicate_id"] += 1  # keep the later row, as the Sheet would
        by_id[job_id] = row

    plan.rows = list(by_id.values())
    return plan


def check_guard(
    publishable: int, current: int, settings: PublishSettings, *, force: bool = False
) -> None:
    """Refuse to replace a healthy copy with an empty or collapsed one.

    Zero rows is refused even with `force`. A collapse below the ratio is refused unless `force`.
    """
    if current < settings.guard_min_existing:
        return
    if publishable == 0:
        raise GuardError(
            f"Refusing to publish 0 rows: Neon currently holds {current}. "
            "Check the Sheet read before retrying."
        )
    if not force and publishable < current * settings.guard_min_ratio:
        raise GuardError(
            f"Publishable rows ({publishable}) are below {settings.guard_min_ratio:.0%} of the "
            f"current {current}. Rerun with --force if this clean-up is deliberate."
        )
